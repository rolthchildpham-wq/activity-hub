'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.join(__dirname,'..','topkey/sports/diy-vlog');
const script=fs.readFileSync(path.join(root,'vlog-csv-import.js'),'utf8');
const page=fs.readFileSync(path.join(root,'index.html'),'utf8');
const ctx={window:{}};vm.createContext(ctx);new vm.Script(script).runInContext(ctx);
const {parseCSV,validateFile}=ctx.window.TopkeyVlogCSV;
const header=['Hạng','Tên','Loại','Đơn vị','Xem','Thích','Chia sẻ','Điểm','TikTok'];
const row=['1','Bacpham','Đội','Tv','1470','155','13','168','https://vt.tiktok.com/ZSpqUnyWQ/'];
const quote=s=>'"'+String(s).replace(/"/g,'""')+'"';
const csv='\ufeff'+[header,row,['2','Bạn "A", thử','Cá nhân','Đơn vị A','0','22','9','31','']].map(r=>r.map(quote).join(',')).join('\r\n');
const parsed=parseCSV(csv);
assert.equal(parsed.length,3);
assert.equal(parsed[2][1],'Bạn "A", thử');
const preview=validateFile(csv,{});
assert.equal(preview.planned.length,2);
assert.equal(preview.errors.length,0);
assert.equal(preview.planned[0].name,'Bacpham');
assert.equal(preview.planned[0].views,1470);
assert.equal(preview.planned[0].url,row[8]);
assert.equal(preview.planned[1].name,'Bạn "A", thử');
assert.equal(preview.planned[1].shares,9);
assert.equal(preview.skipped.length,0);
const repeat=validateFile(csv,{x:{name:'Bacpham',type:'Đội',dept:'Tv',url:row[8]}});
assert.equal(repeat.planned.length,1);
assert.equal(repeat.skipped.length,1);
const bad=validateFile([header,['1','Bad','Đội','Test','-4','3','0','-1','javascript:alert(1)']].map(r=>r.map(quote).join(',')).join('\n'),{});
assert.equal(bad.errors.length,1);
assert.equal(bad.planned.length,0);
assert.throws(()=>validateFile('"Tên","Loại"\n"A","Đội"',{}),/Thiếu cột/);
assert.throws(()=>parseCSV('"incomplete'),/dấu nháy đóng/);
assert(page.includes('id="import-csv"')&&page.includes('id="import-csv-file"'));
assert(page.includes('id="import-csv-confirm"')&&page.includes('id="import-csv-preview"'));
assert(page.includes('window.TopkeyVlogImportGuard='));
assert(page.includes('requireAdmin();'));
assert(page.includes("await entriesRef.update(updates)"));
assert(!page.includes("await entriesRef.set(updates)"));
assert(page.includes("if(importButton)importButton.hidden=!isAdmin||shareMode||testMode"));
assert(page.includes('id="tiktok-test-tools"')&&page.includes('id="tiktok-scan-errors"'));
assert(page.includes('class="container hero-flex"'));
for(const m of page.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g))if(m[1].trim())new vm.Script(m[1]);
console.log('PASS CSV import: BOM Excel roundtrip, quoted commas/newlines, columns, TikTok short link, duplicate skip, invalid rows rejected; append-only admin UI and compact hero retained');
