'use strict';
const fs=require('fs'),assert=require('node:assert/strict'),vm=require('node:vm'),path=require('node:path');
const base=path.join(__dirname,'..','topkey','sports','diy-vlog');
const src=fs.readFileSync(path.join(base,'vlog-i18n.js'),'utf8');
const html=fs.readFileSync(path.join(base,'index.html'),'utf8');
let callback=null,recorded=[];
const context={window:{dispatchEvent:e=>recorded.push(e.type)},document:{readyState:'loading',addEventListener:(name,fn)=>{if(name==='DOMContentLoaded')callback=fn}},localStorage:{getItem:()=> 'vi'},console,WeakMap,MutationObserver:class{},CustomEvent:class{constructor(type,x){this.type=type;this.detail=x?.detail}}};
vm.createContext(context);vm.runInContext(src,context);
const i=context.window.TopkeyVlogI18n;
assert(i?.installed);
assert.equal(i.translate('Top 3 dẫn đầu','en'),'Top 3 leaders');
assert.equal(i.translate('Top 3 dẫn đầu','zh'),'前三名');
assert.equal(i.translate('Top 3 dẫn đầu','vi'),'Top 3 dẫn đầu');
assert.equal(i.translate('1.469 xem · 155 thích · 13 chia sẻ','en'),'1.469 views · 155 likes · 13 shares');
assert.equal(i.translate('75 xem · 10 thích · 5 chia sẻ','zh'),'75 播放 · 10 点赞 · 5 分享');
assert.match(i.translate('ĐANG QUÉT 75/1000 URL · 25 luồng','en'),/^SCANNING 75\/1000/);
assert.match(i.translate('TẠM DỪNG 100/1000 URL','zh'),/^已暂停 100\/1000/);
assert.equal(i.translate('Nguyễn Văn A','en'),'Nguyễn Văn A');
assert.equal(i.translate('https://vt.tiktok.com/example','en'),'https://vt.tiktok.com/example');
assert(html.includes('data-lang="vi"')&&html.includes('data-lang="en"')&&html.includes('data-lang="zh"'));
assert(html.includes('vlog-i18n.js?v=vi-en-zh-scanerrors-20261115'));
assert(!html.includes('translate="no"'));
assert(src.includes("topkey_ui_language_v1"));
assert(!src.includes(".pod .person,#rows td strong,#rows td .muted"),'Video titles and contestant names must be eligible for translation');
console.log('PASS Vlog i18n: VI/EN/ZH + shared language preference; scores and URLs unchanged; names eligible for translation; scan progress translated; responsive picker');
