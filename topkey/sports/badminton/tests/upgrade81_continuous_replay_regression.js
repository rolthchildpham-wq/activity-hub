const fs=require('fs'),path=require('path'),assert=require('assert');
const root=path.resolve(__dirname,'..');
const u77=fs.readFileSync(path.join(root,'src/upgrade77.js'),'utf8');
const u81=fs.readFileSync(path.join(root,'src/upgrade81.js'),'utf8');
const index=fs.readFileSync(path.join(root,'index.html'),'utf8');
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
assert(index.indexOf('src/upgrade80.js')<index.indexOf('src/upgrade81.js'),'Upgrade81 must load after Upgrade80');
assert(/PRE_MS=6000,POST_MS=4000,SEGMENT_MS=3000,KEEP_MS=26000/.test(u77),'~10 second replay timing contract missing');
assert(u77.includes('Replay vòng ~10 giây')&&u77.includes('Lưu replay ~10s'),'10-second replay UI labels missing');
assert((u77.match(/new MediaRecorder\(/g)||[]).length===1,'Replay must keep exactly one MediaRecorder encoder path');
assert(u77.includes('playReplayPlaylist')&&u77.includes('tải từ bộ nhớ local · phát an toàn'),'safe sequential replay path missing');
assert(!u77.includes('appendBuffer(')&&!u77.includes('new MediaSource('),'Upgrade85 must supersede unsafe MSE stitching of independent recorder files');
assert(u77.includes('currentPlaylistToken')&&u77.includes('releaseReplayUrl'),'replay cancellation/resource guard missing');
assert(!/App\.score\s*=/.test(u81)&&!/queueSet|queueMulti/.test(u81),'Upgrade81 must not mutate score/Firebase match state');
assert(sw.includes('./src/upgrade81.js')&&sw.includes('./tests/upgrade81_continuous_replay_regression.js'),'SW missing Upgrade81 assets');
const reg=JSON.parse(fs.readFileSync(path.join(root,'FEATURE_REGISTRY.json'),'utf8'));
assert(reg.features.some(x=>x.id==='CONTINUOUS_REPLAY_001'),'CONTINUOUS_REPLAY_001 missing');
const contract=JSON.parse(fs.readFileSync(path.join(root,'REGRESSION_CONTRACT.json'),'utf8'));
assert(contract.tests.some(x=>x.id==='CONTINUOUS_REPLAY_001'&&x.required),'required continuous replay regression missing');
console.log('upgrade81 replay regression: PASS · ~10s target + safe segment playlist supersedes MSE + one encoder');
