'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const base=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(base,'sports/diy-vlog/index.html'),'utf8');
const hub=fs.readFileSync(path.join(base,'index.html'),'utf8');
const diy=fs.readFileSync(path.join(base,'sports/vnext/index.html'),'utf8');
const rules=JSON.parse(fs.readFileSync(path.join(base,'firebase.database.rules.json'),'utf8'));
const vlog=rules.rules.topkey_handmade_vnext_2026.vlog2026;
assert.ok(html.includes('Bảng xếp hạng <span>Vlog TikTok</span>'));
assert.ok(html.includes('Top 3 dẫn đầu'));
assert.ok(html.includes('TỔNG ĐIỂM'));
assert.ok(html.includes('id="admin-toggle"'));
assert.ok(html.includes('id="admin-sign-in"'), 'Viewer must have a way to log in as ADMIN on a new preview origin');
assert.ok(html.includes('id="admin-login-form"'), 'Login must be available without prior Firebase session');
assert.ok(html.includes('signInWithEmailAndPassword(email,pass)'), 'Use Firebase Auth, never a hardcoded admin password');
assert.ok(html.includes("String(p.role||'').toUpperCase()==='ADMIN'"), 'Permissions must be verified from Firebase profile');
assert.ok(html.includes('id="admin-sign-out"'), 'Admin should be able to sign out from Vlog');
assert.ok(html.includes("if(!isAdmin)return showAdminLogin()"), 'Admin editor remains protected from viewer');

assert.ok(html.includes('id="entry-form"'));
assert.ok(!html.includes('preview.emergentagent.com'));
assert.ok(!html.includes('<iframe'));
assert.ok(hub.includes('href="./sports/diy-vlog/index.html"'));
assert.ok(diy.includes("get('sport')!=='handmade'"));
assert.equal(vlog['.read'],true);
assert.ok(vlog['.write'].includes("=== 'ADMIN'"));
assert.ok(vlog['.write'].includes("=== 'BTC'"), 'Scoped DIY BTC must be eligible');
assert.ok(vlog['.write'].includes("=== 'handmade'"), 'BTC must be explicitly scoped to handmade');
assert.ok(!vlog['.write'].includes("=== 'football'"), 'Cross-sport BTC must not gain Vlog access');
assert.ok(html.includes("role==='BTC'&&scope==='handmade'"), 'Client view must mirror the scoped role policy');
assert.ok(html.includes("id=\"admin-login-form\""), 'Preview login form is required');
assert.ok(html.includes('signInWithEmailAndPassword(email,pass)'), 'Firebase sign-in required');

assert.ok(!vlog['.write'].includes('auth == null'));
assert.ok(!vlog['.write'].includes('auth === null'));
assert.ok(vlog.weights && vlog.entries);
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)];
assert.ok(scripts.length>=1);
for(const [i,match] of scripts.entries())new vm.Script(match[1],{filename:'diy-vlog-inline-'+i+'.js'});
console.log('PASS: native Vlog screenshot layout, no iframe, Hub/DIY links, rules and inline JS syntax');
