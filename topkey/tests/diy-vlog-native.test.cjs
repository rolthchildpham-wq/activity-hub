'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const base=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(base,'sports/diy-vlog/index.html'),'utf8');
const hub=fs.readFileSync(path.join(base,'index.html'),'utf8');
const diy=fs.readFileSync(path.join(base,'sports/vnext/index.html'),'utf8');
const rules=JSON.parse(fs.readFileSync(path.join(base,'firebase.database.rules.json'),'utf8'));
const vlog=rules.rules.topkey_handmade_vnext_2026.vlog2026;
assert.ok(html.includes('Bảng xếp hạng <span>Vlog TikTok</span>'));
assert.ok(html.includes('Top 3 dẫn đầu'));
assert.ok(html.includes('TỔNG ĐIỂM'));
assert.ok(html.includes('id="admin-toggle"'));
assert.ok(html.includes('id="entry-form"'));
assert.ok(!html.includes('preview.emergentagent.com'));
assert.ok(!html.includes('<iframe'));
assert.ok(hub.includes('href="./sports/diy-vlog/index.html"'));
assert.ok(diy.includes("get('sport')!=='handmade'"));
assert.equal(vlog['.read'],true);
assert.ok(vlog['.write'].includes("=== 'ADMIN'"));
assert.ok(!vlog['.write'].includes('auth == null'));
assert.ok(!vlog['.write'].includes('auth === null'));
assert.ok(vlog.weights && vlog.entries);
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)];
assert.ok(scripts.length>=1);
for(const [i,match] of scripts.entries())new vm.Script(match[1],{filename:'diy-vlog-inline-'+i+'.js'});
console.log('PASS: native Vlog screenshot layout, no iframe, Hub/DIY links, rules and inline JS syntax');
