'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.join(__dirname,'..');
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const shared=read('topkey-shared-auth.js'),platform=read('topkey-platform-core.js');
const badminton=read('sports/badminton/index.html'),vnext=read('sports/vnext/index.html');
const rules=JSON.parse(read('firebase.database.rules.json')).rules;
assert.match(shared,/const authRoot=\(\)=>\s*'topkey_badminton_vnext_2026'/,'All sports must read central profiles');
assert.doesNotMatch(shared,/location\.replace\('\.\.\/\.\.\/index\.html\?access=denied/,'Do not redirect an authenticated user on scope denial');
assert.match(shared,/this\._showVerificationPending\(this\._accessDeniedMessage\)/);
assert.match(shared,/auth\.onAuthStateChanged/);
assert.match(shared,/setPersistence\(p\)/);
assert.match(badminton,/mobile-stability-h140\.css/);
assert.match(badminton,/topkey-shared-auth\.js\?v=h140-unified-mobile-20261115/);
assert.match(vnext,/topkey-shared-auth\.js\?v=h140-unified-mobile-20261115/);
const css=read('sports/badminton/mobile-stability-h140.css');
assert.match(css,/@media \(max-width: 767px\)/);
assert.match(css,/overflow-x:auto/);
const sandbox={window:{},document:{},console,setTimeout,clearTimeout};
vm.runInNewContext(platform,sandbox);
const p=sandbox.window.TopkeyPlatform.policy;
const sports=['badminton','football','volleyball','running','handmade','shuttle','cooking'];
const admin={role:'ADMIN',active:true};
for(const sport of sports)assert.equal(p.canAccess(admin,sport),true,'ADMIN blocked from '+sport);
for(const sport of sports)assert.equal(p.canAccess({...admin,disabled:true},sport),false);
assert.equal(p.canAccess({role:'BTC',sportScope:'football',active:true},'football'),true);
assert.equal(p.canAccess({role:'BTC',sportScope:'football',active:true},'badminton'),false);
for(const sport of sports){const key='topkey_'+sport+'_vnext_2026';assert.ok(rules[key],key+' missing');const str=JSON.stringify(rules[key]);assert.match(str,/topkey_badminton_vnext_2026\/users/,'Rules should resolve permissions against central profile: '+sport);}
console.log('PASS 7 ADMIN sports, disabled policy, BTC scope, shared mobile auth source, CSS and central Firebase rule references');
