'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const hub=fs.readFileSync(path.join(root,'index.html'),'utf8');
const exec=fs.readFileSync(path.join(root,'executive-dashboard.js'),'utf8');
const insight=fs.readFileSync(path.join(root,'executive-sport-insights.js'),'utf8');
const css=fs.readFileSync(path.join(root,'executive-sport-insights.css'),'utf8');
const keys=['football','badminton','volleyball','running','cooking','handmade','shuttle'];
for(const k of keys)assert.match(insight,new RegExp(' '+k+':\\{title:'),'Missing sport insight '+k);
assert.match(hub,/executive-sport-insights\.js\?v=20261117-r1/);
assert.match(hub,/executive-sport-insights\.css\?v=20261117-r1/);
assert(hub.indexOf('executive-sport-insights.js')<hub.indexOf('executive-dashboard.js'),'Insight renderer must load before dashboard');
assert.match(exec,/TopkeyExecutiveSportInsights\?\.render\(b,data\)/);
assert.match(insight,/data\.clubs\.find/);
assert.match(insight,/data\.events\.filter/);
assert.doesNotMatch(insight,/firebase\.|\.ref\(|fetch\(|localStorage|sessionStorage|innerHTML|\.set\(|\.update\(/,'Sport report renderer must be read-only, DOM safe');
assert.match(css,/@media\(max-width:850px\)/);
assert.match(css,/\[aria-pressed="true"\]/);
new vm.Script(insight,{filename:'executive-sport-insights.js'});
console.log('PASS executive sport insights: 7 sports, dashboard load order, no write/network APIs, responsive CSS and JS syntax');
