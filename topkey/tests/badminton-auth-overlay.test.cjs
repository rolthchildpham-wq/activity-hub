const assert=require('node:assert/strict');
const fs=require('node:fs');
const legacy=fs.readFileSync('topkey/sports/badminton/index.html','utf8');
const shared=fs.readFileSync('topkey/sports/vnext/index.html','utf8');
assert.ok(legacy.includes("query.set('sport', 'badminton')"),'legacy route must redirect to shared VNext');
assert.ok(legacy.includes('../vnext/index.html'),'legacy route target is the shared VNext workspace');
assert.ok(!legacy.includes('topkey-auth-boot-pending')&&!legacy.includes('topkey-auth-boot-cleanup'),'legacy route must not render an independent auth overlay');
assert.ok(shared.includes('topkey-shared-auth.js'),'shared VNext retains the common Firebase authentication service');
assert.ok(shared.includes('id="login-screen"'),'shared VNext retains the login screen');
assert.ok(shared.includes('id="app-shell"'),'shared VNext retains the authenticated application shell');
console.log('Legacy badminton auth overlay retired; shared VNext auth flow retained.');
