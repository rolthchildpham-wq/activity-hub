"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs"),vm=require("node:vm"),path=require("node:path");
const base=path.resolve(__dirname,"..");
const html=fs.readFileSync(path.join(base,"sports/diy-vlog/index.html"),"utf8");
const browser=fs.readFileSync(path.join(base,"sports/diy-vlog/tiktok-automation.js"),"utf8");
const server=fs.readFileSync(path.join(base,"functions/index.js"),"utf8");
const config=JSON.parse(fs.readFileSync(path.join(base,"firebase.tiktok.functions.json"),"utf8"));
assert.equal(config.functions[0].source,"functions");
assert.ok(html.includes('id="tiktok-connect"'));
assert.ok(html.includes('id="tiktok-sync-now"'));
assert.ok(html.includes("firebase-functions-compat.js"));
assert.ok(html.includes("tiktok-automation.js"));
assert.ok(html.includes("raw.entries||{}"),"Empty tournament must render before first entry");
assert.ok(browser.includes("httpsCallable(name)"));
assert.ok(browser.includes("tiktokCreateCreatorLink"));
assert.ok(browser.includes("tiktokSyncNow"));
assert.ok(server.includes("https://open.tiktokapis.com/v2/video/query/"));
assert.ok(server.includes("https://open.tiktokapis.com/v2/oauth/token/"));
assert.ok(server.includes('schedule:"every 6 hours"'));
assert.ok(server.includes('scope:"video.list,user.info.basic"'));
assert.ok(server.includes('PRIVATE="_topkey_private/tiktok2026"'));
assert.ok(server.includes('token')||server.includes('Token'));
assert.ok(!html.includes("TIKTOK_CLIENT_SECRET"),"Secret must not reach browser");
assert.ok(!browser.includes("TIKTOK_CLIENT_SECRET"),"Secret must not reach browser");
assert.ok(!server.includes("tiktok.com/@"+ "sample-user"),"No fabricated TikTok data");
new vm.Script(browser,{filename:"tiktok-automation.js"});
new vm.Script(server,{filename:"functions/index.js"});
const rules=JSON.parse(fs.readFileSync(path.join(base,"firebase.database.rules.json"),"utf8")).rules;
const vlog=rules.topkey_handmade_vnext_2026.vlog2026;
assert.equal(vlog[".read"],true);
assert.ok(vlog[".write"].includes("=== 'ADMIN'"));
assert.ok(vlog[".write"].includes("=== 'handmade'"));
assert.ok(!rules._topkey_private,"The token storage has no client-access rules");
console.log("PASS TikTok consent, official metric sync, protected credentials and opt-in deployment config");
